const languageCodes={ua:"uk",pl:"pl",ru:"ru",en:"en"};
let currentLanguage="ua";
let gallery=[];

function setLanguage(lang){
  if(!translations[lang])lang="ua";
  currentLanguage=lang;
  const t=translations[lang];
  document.documentElement.lang=languageCodes[lang];
  document.querySelectorAll("[data-t]").forEach(el=>{const value=t[el.dataset.t];if(value)el.textContent=value});
  document.querySelectorAll("[data-lang]").forEach(button=>button.classList.toggle("active",button.dataset.lang===lang));
  document.getElementById("pricingGrid").innerHTML=packages[lang].map((pack,i)=>`
    <article class="pricing-card ${i===3?"featured":""}">
      <div class="package-top"><span>0${i+1}</span>${i===3?"<em>MAX</em>":""}</div>
      <h3>${pack[0]}</h3><strong>${pack[1]}</strong>
      <ul>${pack[2].map(item=>`<li>${item}</li>`).join("")}</ul>
      <p>${t.priceNote}</p><a href="#contact">${t.cta}<b>↗</b></a>
    </article>`).join("");
  document.querySelectorAll(".media-photo img").forEach(img=>img.alt=t.galleryAlt);
  localStorage.setItem("eraevent-language",lang);
}

function renderGallery(){
  const grid=document.getElementById("mediaGrid");
  grid.innerHTML=gallery.map(item=>`
    <button class="media-photo" data-full="./assets/${item.file}" style="--x:${item.x}%;--y:${item.y}%;--zoom:${item.zoom/100}">
      <img src="./assets/${item.file}" alt="${translations[currentLanguage].galleryAlt}" loading="lazy">
    </button>`).join("");
  grid.querySelectorAll(".media-photo").forEach(button=>button.addEventListener("click",()=>openLightbox(button.dataset.full)));
}

async function loadGallery(){
  try{
    const response=await fetch("./gallery-settings.json");
    if(!response.ok)throw new Error("Gallery settings unavailable");
    gallery=await response.json();
  }catch{
    gallery=Array.from({length:9},(_,i)=>({file:`gallery-${String(i+1).padStart(2,"0")}.webp`,x:50,y:50,zoom:115}));
  }
  renderGallery();
}

